/** 2015 标准级别工资（级·档，下标从 1 计） */
export function levelWage2015(level: number, grade: number): number {
  const arr = LEVEL_SALARY[level];
  if (!arr || grade < 1 || grade > arr.length) return 0;
  return arr[grade - 1];
}

/** 2015 标准职务工资（按职务名称 + 领导/非领导） */
export function dutyWage2015ByName(name: string, isLeader: boolean): number {
  const s = POSITION_SALARY[name];
  if (!s) return 0;
  return isLeader ? (s.leader ?? s.nonLeader ?? 0) : (s.nonLeader ?? s.leader ?? 0);
}
